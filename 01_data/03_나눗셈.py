"""
숫자를 나눌 떼 원하는 결과의 형태에 따라 연산자(계산기호)가 달라진다

상식적으로 10/3===> 3.33333이여야 한다

프로그래밍에서는 소수점 유무에 따라 형태가 달라진다
- 정수 : 소수점이 없는 숫자 (ex : int)
- 실수 : 소수점에 있는 숫자 (ex : float)

프로그래밍 상에서 이걸을 확인하는 명령이 있다 - type()
"""

a=10
print(type(a)) #int

b=10.5
print(type(b)) #float

c=10 #int
d=3 #int
print(c/d) # 일반 나눗셈에서는 소수점이 나옴(결과가 실수 형태) float
print(c//d) # 정수가 필요한 경우의 나눗셈(몫) int
print(c%d) #int
