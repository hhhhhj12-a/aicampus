'''
섭씨를 화씨로 변환하기 (02_입력실습문제1.py)
섭씨온도를 입력받아 화씨온도로 변환하여 출력하세요.
계산식: 화씨 = 섭씨 × 1.8 + 32
'''

# 섭씨온도 입력받기
celsius = float(input('섭씨온도:'))

# 화씨온도 계산하기
fahrenheit = celsius * 1.8 + 32

# 결과 출력하기
print(fahrenheit)

#강사님 풀이
#입력
#c=input('섭씨온도입력 :') #불가능
c=int(input('섭씨온도입력 : ')) #가능

#연산
f=c*1.8+32

#출력
print('화씨', f)
